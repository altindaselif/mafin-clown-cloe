let currentPatternIndex = 0;
let currentPatternName = "fina";
let activePattern = patternData[currentPatternName];

function handlePatternSelection(event) {
  // target yerine currentTarget kullanıyoruz! Böylece içindeki yazıya da tıklasalar JS direkt butonu yakalar.
  const btn = event.currentTarget;
  const selectedPattern = btn.dataset.pattern;

  // Eğer pattern verisi yoksa veya zaten seçili olanlaysa işlem yapma
  if (!selectedPattern || currentPatternName === selectedPattern) return;

  currentPatternName = selectedPattern;
  activePattern = patternData[currentPatternName];
  currentPatternIndex = 0;

  // Tüm butonlardan active class'ını sil ve SADECE tıklanana ekle
  document
    .querySelectorAll(".pattern-btn")
    .forEach((b) => b.classList.remove("active"));
  btn.classList.add("active");

  // Eğer domatesler çizilmeye başlandıysa ekranı şıkır şıkır temizle
  if (typeof window.clearTomatoes === "function") {
    window.clearTomatoes();
  }
}

function getNextPatternCoordinate(canvasWidth, canvasHeight) {
  if (currentPatternIndex >= activePattern.length) {
    return null;
  }

  const point = activePattern[currentPatternIndex];

  const pixelX = (point.x / 100) * canvasWidth;
  const pixelY = (point.y / 100) * canvasHeight;

  currentPatternIndex++;

  return { x: pixelX, y: pixelY };
}

function initPatternButtons() {
  const buttons = document.querySelectorAll(".pattern-btn");
  buttons.forEach((button) => {
    button.addEventListener("click", handlePatternSelection);
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initPatternButtons);
} else {
  initPatternButtons();
}
